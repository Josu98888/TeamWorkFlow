import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayUnique,
  IsArray,
  IsBoolean,
  IsInt,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  IsUUID,
  Max,
  MaxLength,
  Min,
  Validate,
  ValidatorConstraint,
} from 'class-validator';
import type { ValidatorConstraintInterface } from 'class-validator';
import { isIanaTimezone } from '../site-policy';

@ValidatorConstraint({ name: 'isIanaTimezone', async: false })
export class IsIanaTimezoneConstraint implements ValidatorConstraintInterface {
  validate(value: unknown) {
    return isIanaTimezone(value);
  }

  defaultMessage() {
    return 'timezone must be a valid IANA time zone';
  }
}

export const MAX_GEOFENCE_RADIUS_METERS = 10_000;
export const MAX_PAGE_SIZE = 100;
export const DEFAULT_PAGE_SIZE = 20;

// HTTP body of `POST /sites`. The tenant comes from the actor; the QR is
// generated by the service.
export class CreateSiteBodyDto {
  @IsString()
  @IsNotEmpty()
  @MaxLength(120)
  name!: string;

  @IsString()
  @IsNotEmpty()
  @MaxLength(300)
  address!: string;

  @IsNumber()
  @Min(-90)
  @Max(90)
  latitude!: number;

  @IsNumber()
  @Min(-180)
  @Max(180)
  longitude!: number;

  @IsInt()
  @Min(1)
  @Max(MAX_GEOFENCE_RADIUS_METERS)
  geofenceRadiusMeters!: number;

  @Validate(IsIanaTimezoneConstraint)
  timezone!: string;
}

// HTTP body of `PATCH /sites/:siteId`. `isActive: false` deactivates the site
// (sites are never deleted). The QR is not editable here (see rotate-qr).
export class UpdateSiteBodyDto {
  @IsOptional()
  @IsString()
  @IsNotEmpty()
  @MaxLength(120)
  name?: string;

  @IsOptional()
  @IsString()
  @IsNotEmpty()
  @MaxLength(300)
  address?: string;

  @IsOptional()
  @IsNumber()
  @Min(-90)
  @Max(90)
  latitude?: number;

  @IsOptional()
  @IsNumber()
  @Min(-180)
  @Max(180)
  longitude?: number;

  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(MAX_GEOFENCE_RADIUS_METERS)
  geofenceRadiusMeters?: number;

  @IsOptional()
  @Validate(IsIanaTimezoneConstraint)
  timezone?: string;

  @IsOptional()
  @IsBoolean()
  isActive?: boolean;
}

export class SiteIdParamDto {
  @IsUUID()
  siteId!: string;
}

export class PostIdParamDto {
  @IsUUID()
  postId!: string;
}

// Query of the paginated lists (`GET /sites`, `GET /sites/:siteId/posts`).
export class PageQueryDto {
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  page?: number;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(MAX_PAGE_SIZE)
  pageSize?: number;
}

export class CreatePostBodyDto {
  @IsString()
  @IsNotEmpty()
  @MaxLength(120)
  name!: string;

  @IsOptional()
  @IsArray()
  @ArrayMaxSize(50)
  @ArrayUnique()
  @IsString({ each: true })
  @IsNotEmpty({ each: true })
  @MaxLength(60, { each: true })
  requiredSkills?: string[];

  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(1000)
  minPeople?: number;
}

export class UpdatePostBodyDto {
  @IsOptional()
  @IsString()
  @IsNotEmpty()
  @MaxLength(120)
  name?: string;

  @IsOptional()
  @IsArray()
  @ArrayMaxSize(50)
  @ArrayUnique()
  @IsString({ each: true })
  @IsNotEmpty({ each: true })
  @MaxLength(60, { each: true })
  requiredSkills?: string[];

  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(1000)
  minPeople?: number;

  @IsOptional()
  @IsBoolean()
  isActive?: boolean;
}
